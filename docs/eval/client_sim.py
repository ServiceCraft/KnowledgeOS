report = []
for name, turns in SCENARIOS:
    sid = http("POST", "/admin/bot/chat/sessions", {"title": "client-sim-" + name}, TOKEN)["data"]["id"]
    convo = []
    for turn in turns:
        data = http("POST", f"/admin/bot/chat/sessions/{sid}/messages", {"content": turn}, TOKEN)["data"]
        msg = data.get("message") or {}
        state = (data.get("session") or {}).get("state", "")
        convo.append({
            "user": turn,
            "bot": msg.get("content") or "",
            "guardrail": msg.get("guardrail_action", ""),
            "reason": msg.get("refusal_reason") or "",
            "state": state,
            "sources": len(msg.get("sources") or []),
        })
        if state in ("waiting_operator", "operator"):
            break
    report.append({"scenario": name, "session_id": sid, "dialog": convo})
    print("done:", name, flush=True)

with open("client_sim_report.json", "w") as f:
    json.dump(report, f, ensure_ascii=False, indent=2)
